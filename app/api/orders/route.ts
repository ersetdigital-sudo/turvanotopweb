import { NextResponse } from "next/server";
import { apiError, readJsonBody, serverError } from "@/lib/api";
import { buildPublicOrder } from "@/lib/public-order";
import { insertOrder, readOrder } from "@/lib/supabase/store";

/**
 * Creates the order a customer just checked out. Public on purpose, so nothing
 * from the browser is trusted: price, status, and SN are rebuilt on the server
 * (see lib/public-order.ts). Only an admin can mark an order done and add SN.
 */
export async function POST(request: Request) {
  try {
    const result = await buildPublicOrder(await readJsonBody(request));
    if ("error" in result) return apiError(result.error);

    // The ID is generated by the client, so guard against the rare collision
    // instead of silently overwriting someone else's order.
    if (await readOrder(result.order.id)) {
      return apiError(`ID transaksi ${result.order.id} sudah terpakai. Silakan ulangi transaksi.`, 409);
    }

    const created = await insertOrder(result.order);
    return NextResponse.json({ order: created }, { status: 201 });
  } catch (error) {
    return serverError(error);
  }
}
